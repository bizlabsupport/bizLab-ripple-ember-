
create table if not exists ember.backfill_batch (
  location_id text not null references ember.location(location_id) on delete cascade,
  batch_id text not null,
  fieldroutes_office_id text not null,
  status text not null default 'receiving' check (status in ('receiving','complete','failed')),
  expected_count integer,
  received_count integer not null default 0,
  imported_count integer not null default 0,
  rejected_count integer not null default 0,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  error_summary jsonb not null default '[]'::jsonb,
  primary key (location_id,batch_id),
  check (expected_count is null or expected_count > 0)
);

create table if not exists ember.backfill_record (
  id bigint generated by default as identity primary key,
  location_id text not null,
  batch_id text not null,
  fieldroutes_customer_id text not null,
  record_hash text,
  status text not null check (status in ('imported','rejected')),
  error text,
  processed_at timestamptz not null default now(),
  unique (location_id,batch_id,fieldroutes_customer_id),
  foreign key (location_id,batch_id)
    references ember.backfill_batch(location_id,batch_id)
    on delete cascade
);

alter table ember.backfill_batch enable row level security;
alter table ember.backfill_record enable row level security;

comment on table ember.backfill_batch is
'Ember-only audit and completion gate for FieldRoutes historical customer/service backfills. Completion never enables sending.';
comment on table ember.backfill_record is
'Idempotency and per-customer outcome log for an Ember historical backfill; raw PII is not duplicated here.';

